"""A0-03b: the same 4-wheel car, two reference scenes, MuJoCo 4.0.0 vs Godot 4.7.2 + Jolt. Measurement only.

    uv run spikes/godot-jolt/car.py --json spikes/godot-jolt/results/a0-03b-car.json

The scene parameters live in car_scene.json (generated by `car.py --write-params`, checked by test_car.py) and are read by
this file (MuJoCo) and by car.gd (Godot), so both engines get the same numbers. Z up, SI, timestep 0.002 s (500 Hz).

Scenes
  slope  the car starts at rest on a 10 degree incline, 1 m below the origin along the slope, and the two rear wheels get a
         constant torque for 4 s (drives uphill).
  drop   the same car, no torque, released 1.0 m above a flat floor with a small roll/pitch and 1 m/s forward speed, 3 s.

Comparison: chassis position and orientation at every step (step 0 = before the first step). Positions are meters, the
orientation difference is the geodesic angle between the two chassis quaternions (rad).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import math
import os
import platform
import subprocess
import sys
import tempfile
from pathlib import Path

import mujoco
import numpy as np

HERE = Path(__file__).resolve().parent
PARAMS_PATH = HERE / "car_scene.json"
DEFAULT_GODOT = Path.home() / ".cache" / "kinetra-godot" / "Godot.app" / "Contents" / "MacOS" / "Godot"
DT = 0.002


def quat_mul(a, b):
    aw, ax, ay, az = a
    bw, bx, by, bz = b
    return [aw * bw - ax * bx - ay * by - az * bz, aw * bx + ax * bw + ay * bz - az * by,
            aw * by - ax * bz + ay * bw + az * bx, aw * bz + ax * by - ay * bx + az * bw]


def quat_axis(axis, angle):
    s = math.sin(angle / 2)
    return [math.cos(angle / 2), axis[0] * s, axis[1] * s, axis[2] * s]


def quat_rotate(q, v):
    w, x, y, z = q
    # v' = q v q*
    t = [2 * (y * v[2] - z * v[1]), 2 * (z * v[0] - x * v[2]), 2 * (x * v[1] - y * v[0])]
    return [v[0] + w * t[0] + (y * t[2] - z * t[1]), v[1] + w * t[1] + (z * t[0] - x * t[2]),
            v[2] + w * t[2] + (x * t[1] - y * t[0])]


def make_params() -> dict:
    """All scene numbers. Wheel layout: x = +-0.35 (front +x), y = +-0.30, z = -0.05 in the chassis frame."""
    theta = math.radians(10.0)
    ground_q = quat_axis([0, 1, 0], -theta)  # +x is uphill
    clearance = 0.0005  # wheel bottom above the surface at the start
    chassis_h = 0.2 + clearance  # chassis center above the surface: wheel center 0.15 + 0.05 lower than chassis center
    local = [-1.0, 0.0, chassis_h]
    slope_pos = quat_rotate(ground_q, local)
    drop_q = quat_mul(quat_axis([0, 1, 0], math.radians(5.0)), quat_axis([1, 0, 0], math.radians(3.0)))
    return {
        "dt": DT,
        "gravity": 9.80665,
        "friction": 1.0,
        "restitution": 0.0,
        "chassis": {"half_extents": [0.5, 0.25, 0.1], "mass": 10.0},
        "wheel": {"radius": 0.15, "half_width": 0.05, "mass": 1.0,
                  "positions": {"front_left": [0.35, 0.30, -0.05], "front_right": [0.35, -0.30, -0.05],
                                "rear_left": [-0.35, 0.30, -0.05], "rear_right": [-0.35, -0.30, -0.05]},
                  "drive_wheels": ["rear_left", "rear_right"], "axis_in_chassis": [0, 1, 0]},
        "scenes": {
            "slope": {"steps": 2000, "ground_quat_wxyz": ground_q, "chassis_pos": slope_pos,
                      "chassis_quat_wxyz": ground_q, "chassis_linvel": [0, 0, 0], "drive_torque_per_wheel": 3.0},
            "drop": {"steps": 1500, "ground_quat_wxyz": [1, 0, 0, 0], "chassis_pos": [0, 0, 1.0 + 0.2],
                     "chassis_quat_wxyz": drop_q, "chassis_linvel": [1.0, 0, 0], "drive_torque_per_wheel": 0.0},
        },
    }


def load_params() -> dict:
    return json.loads(PARAMS_PATH.read_text())


def build_mjcf(p: dict, scene: str, *, timestep: float | None = None, integrator: str = "Euler",
               solref: str | None = None) -> str:
    s = p["scenes"][scene]
    dt = timestep or p["dt"]
    ch, wh = p["chassis"], p["wheel"]
    g = s["ground_quat_wxyz"]
    cq, cp = s["chassis_quat_wxyz"], s["chassis_pos"]
    fr = p["friction"]
    sr = f' solref="{solref}"' if solref else ""
    wheels, motors = [], []
    for name, pos in wh["positions"].items():
        wheels.append(
            f'<body name="{name}" pos="{pos[0]} {pos[1]} {pos[2]}">'
            f'<joint name="j_{name}" type="hinge" axis="0 1 0"/>'
            f'<geom type="cylinder" euler="90 0 0" size="{wh["radius"]} {wh["half_width"]}" mass="{wh["mass"]}"'
            f' friction="{fr} 0 0"{sr}/></body>')
        if name in wh["drive_wheels"]:
            motors.append(f'<motor name="m_{name}" joint="j_{name}" gear="1" ctrllimited="false"/>')
    return f"""<mujoco>
  <option timestep="{dt}" integrator="{integrator}" gravity="0 0 -{p['gravity']}"/>
  <worldbody>
    <geom name="ground" type="plane" size="0 0 0.1" quat="{g[0]} {g[1]} {g[2]} {g[3]}" friction="{fr} 0 0"{sr}/>
    <body name="chassis" pos="{cp[0]} {cp[1]} {cp[2]}" quat="{cq[0]} {cq[1]} {cq[2]} {cq[3]}">
      <freejoint name="root"/>
      <geom type="box" size="{ch['half_extents'][0]} {ch['half_extents'][1]} {ch['half_extents'][2]}" mass="{ch['mass']}" friction="{fr} 0 0"{sr}/>
      {''.join(wheels)}
    </body>
  </worldbody>
  <actuator>{''.join(motors)}</actuator>
</mujoco>"""


def run_mujoco(p: dict, scene: str, *, dz: float = 0.0, **kw) -> np.ndarray:
    """(steps+1, 7) array: x y z qw qx qy qz of the chassis, row 0 = initial state, row k = after k steps."""
    s = p["scenes"][scene]
    model = mujoco.MjModel.from_xml_string(build_mjcf(p, scene, **kw))
    data = mujoco.MjData(model)
    data.qpos[2] += dz
    data.qvel[0:3] = s["chassis_linvel"]  # free-joint linear velocity is in the world frame
    n = round(s["steps"] * p["dt"] / model.opt.timestep)
    out = np.empty((n + 1, 7))
    out[0] = np.r_[data.qpos[0:3], data.qpos[3:7]]
    tq = s["drive_torque_per_wheel"]
    ctrl = np.full(model.nu, tq)
    for k in range(n):
        if model.nu:
            data.ctrl[:] = ctrl
        mujoco.mj_step(model, data)
        out[k + 1] = np.r_[data.qpos[0:3], data.qpos[3:7]]
    return out


def angle_between(qa: np.ndarray, qb: np.ndarray) -> np.ndarray:
    """Geodesic angle (rad) between two arrays of wxyz quaternions; q and -q are the same rotation."""
    d = np.abs(np.sum(qa * qb, axis=1)) / (np.linalg.norm(qa, axis=1) * np.linalg.norm(qb, axis=1))
    return 2.0 * np.arccos(np.clip(d, -1.0, 1.0))


def diff(a: np.ndarray, b: np.ndarray) -> dict:
    """Trajectory difference a vs b over their common rows (positions m, angles rad)."""
    n = min(len(a), len(b))
    a, b = a[:n], b[:n]
    dp = np.linalg.norm(a[:, 0:3] - b[:, 0:3], axis=1)
    da = angle_between(a[:, 3:7], b[:, 3:7])
    path = float(np.sum(np.linalg.norm(np.diff(a[:, 0:3], axis=0), axis=1)))
    return {
        "rows": n,
        "pos_max_m": float(dp.max()), "pos_max_step": int(dp.argmax()), "pos_final_m": float(dp[-1]),
        "pos_rms_m": float(np.sqrt(np.mean(dp**2))),
        "ang_max_rad": float(da.max()), "ang_final_rad": float(da[-1]),
        "path_length_m": path, "pos_final_over_path": float(dp[-1] / path) if path > 0 else None,
        "pos_max_over_path": float(dp.max() / path) if path > 0 else None,
    }


def read_godot_csv(path: Path) -> np.ndarray:
    return np.loadtxt(path, delimiter=",", skiprows=1)[:, 1:8]


def run_godot(godot: Path, scene: str, out: Path, *, dz: float = 0.0, project: Path | None = None) -> np.ndarray:
    env = {**os.environ, "KINETRA_GUARD_PASSED": os.environ.get("KINETRA_GUARD_PASSED", "1")}
    cmd = [str(godot), "--headless", "--fixed-fps", "500", "--path", str(project or HERE), "--script", str(HERE / "car.gd"),
           "--", "--scene", scene, "--params", str(PARAMS_PATH), "--out", str(out), "--dz", repr(dz)]
    r = subprocess.run(cmd, capture_output=True, text=True, env=env, timeout=600)
    if r.returncode != 0 or not out.is_file():
        raise RuntimeError(f"car.gd failed (exit {r.returncode}): {r.stderr[-400:]} {r.stdout[-400:]}")
    return read_godot_csv(out)


def impact_time(traj: np.ndarray) -> float:
    """Time of the most negative chassis vertical speed (finite difference): when the drop lands."""
    vz = np.diff(traj[:, 2]) / DT
    return float((np.argmin(vz) + 1) * DT)


def decimate(a: np.ndarray, every: int) -> list:
    return [[round(float(v), 6) for v in row] for row in a[::every]]


def machine_spec(godot: Path | None) -> dict:
    def sh(c):
        return subprocess.run(c, shell=True, capture_output=True, text=True).stdout.strip()
    spec = {"cpu": sh("sysctl -n machdep.cpu.brand_string") or platform.processor(), "os": platform.platform(),
            "python": platform.python_version(), "mujoco": mujoco.__version__, "numpy": np.__version__,
            "loadavg": [round(x, 1) for x in os.getloadavg()]}
    if godot and godot.is_file():
        spec["godot"] = sh(f'"{godot}" --version')
    return spec


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--write-params", action="store_true", help="rewrite car_scene.json from make_params()")
    ap.add_argument("--godot", type=Path, default=Path(os.environ.get("GODOT") or DEFAULT_GODOT))
    ap.add_argument("--json", help="write the results to this file")
    ap.add_argument("--dz", type=float, default=1e-6, help="start-height perturbation of the noise-floor runs (m)")
    ap.add_argument("--decimate", type=int, default=25, help="keep every Nth row of the committed series")
    args = ap.parse_args(argv)
    if args.write_params:
        PARAMS_PATH.write_text(json.dumps(make_params(), indent=1) + "\n")
        return 0
    if not args.godot.is_file():
        print(f"Godot binary not found: {args.godot} (see REPORT.md, 'Godot binary')", file=sys.stderr)
        return 4
    p = load_params()
    results = {"machine": machine_spec(args.godot), "params_sha256": hashlib.sha256(PARAMS_PATH.read_bytes()).hexdigest(),
               "dz_perturbation_m": args.dz, "scenes": {}}
    tmp = Path(tempfile.mkdtemp(prefix="a003b-"))
    try:
        for scene in p["scenes"]:
            mj = run_mujoco(p, scene)
            g1 = run_godot(args.godot, scene, tmp / f"{scene}-1.csv")
            g2 = run_godot(args.godot, scene, tmp / f"{scene}-2.csv")
            gp = run_godot(args.godot, scene, tmp / f"{scene}-dz.csv", dz=args.dz)
            sha = [hashlib.sha256((tmp / f"{scene}-{i}.csv").read_bytes()).hexdigest() for i in ("1", "2")]
            variants = {
                "mujoco_euler_dt0.002 (reference)": mj,
                "mujoco_implicitfast": run_mujoco(p, scene, integrator="implicitfast"),
                "mujoco_dt0.001": run_mujoco(p, scene, timestep=0.001)[::2],
                "mujoco_solref0.004": run_mujoco(p, scene, solref="0.004 1"),
                f"mujoco_start_z+{args.dz:g}": run_mujoco(p, scene, dz=args.dz),
            }
            entry = {
                "steps": len(mj) - 1,
                "godot_same_build_repeat": {"csv_sha256": sha, "identical": sha[0] == sha[1]},
                "godot_vs_mujoco": diff(g1, mj),
                "noise_floor": {
                    "mujoco_vs_mujoco_variants": {k: diff(v, mj) for k, v in variants.items() if v is not mj},
                    f"godot_start_z+{args.dz:g}_vs_godot": diff(gp, g1),
                },
                "godot_final": [round(float(v), 5) for v in g1[-1]], "mujoco_final": [round(float(v), 5) for v in mj[-1]],
                "series_every": args.decimate,
                "series_godot": decimate(g1, args.decimate), "series_mujoco": decimate(mj, args.decimate),
            }
            if scene == "drop":
                entry["impact_time_s"] = {"godot": impact_time(g1), "mujoco": impact_time(mj)}
            results["scenes"][scene] = entry
            d = entry["godot_vs_mujoco"]
            print(f"{scene}: pos max {d['pos_max_m']:.4g} m (step {d['pos_max_step']}), final {d['pos_final_m']:.4g} m, "
                  f"ang max {d['ang_max_rad']:.4g} rad, path {d['path_length_m']:.3g} m; godot repeat identical="
                  f"{entry['godot_same_build_repeat']['identical']}", flush=True)
    finally:
        for f in tmp.glob("*"):
            f.unlink()
        tmp.rmdir()
    if args.json:
        Path(args.json).write_text(json.dumps(results, indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
