"""Export the Project model as JSON Schema files and TypeScript types (C-01d).

    uv run python packages/core/scripts/export_schemas.py            # write schemas/*.schema.json and schemas/types.ts
    uv run python packages/core/scripts/export_schemas.py --check    # write nothing; exit 1 if the files on disk differ

What is exported is not listed anywhere. The script reads `kinetra_core.__all__` and takes every exported
  - pydantic model (`BaseModel` subclass),
  - enum,
  - type alias that pydantic can build a schema for (e.g. the discriminated unions `Distribution`, `TerrainProp`).
A model a later leaf adds to `kinetra_core/__init__.py` therefore appears in `schemas/` with no edit here. Exported
constants, functions and exception classes (`COORDINATE_FRAME`, `load_material_catalog`, ...) carry no schema and are
skipped; any other exported class (a dataclass, a TypedDict) fails the export, so nothing the client may see is left
without a type.

Outputs (`schemas/`, relative to the repository root)
  <Name>.schema.json  one self-contained JSON Schema (draft 2020-12) per exported name, `$defs` included, validation mode
                      (what the core accepts). Keys keep the model's field order; `$defs` are sorted by name.
  types.ts            every named schema as a TypeScript `interface` / `type`, from `schema_to_ts.py`. A field with a
                      default is optional (`?`), because the core accepts a document without it and fills it in.
`schemas/examples/` and `schemas/package.json` are hand-written and never touched. Any other `*.schema.json` or
`types.ts` that the current models do not produce (a model was removed or renamed) is stale: removed on write,
reported by `--check`.
"""

from __future__ import annotations

import argparse
import enum
import json
import sys
import types as pytypes
import typing
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
from schema_to_ts import render_declarations  # noqa: E402

ROOT = Path(__file__).resolve().parents[3]
DEFAULT_OUT = ROOT / "schemas"
SCHEMA_DIALECT = "https://json-schema.org/draft/2020-12/schema"
TYPES_FILE = "types.ts"
SCHEMA_SUFFIX = ".schema.json"

HEADER = """\
// Generated by packages/core/scripts/export_schemas.py from the types exported by kinetra_core. Do not edit.
// Regenerate: uv run python packages/core/scripts/export_schemas.py   (CI runs it with --check)
//
// These types are the Project JSON the core accepts (JSON Schema, validation mode): a field with a default is
// optional here. Units are SI and fixed per field by a literal type, e.g. `unit: "kg/m^3"`; a quaternion is
// `{ x, y, z, w }` (docs/architecture/project-model.md).

"""


class ExportError(RuntimeError):
    """The exported names cannot be turned into a consistent set of schemas."""


def _is_schema_type(obj: Any) -> bool:
    from pydantic import BaseModel

    if isinstance(obj, type):
        return issubclass(obj, (BaseModel, enum.Enum))
    # `Annotated[A | B, Field(discriminator=...)]`, `A | B`, `Literal[...]`: what pydantic can build a schema for
    origin = typing.get_origin(obj)
    return origin is not None and (
        origin in (typing.Annotated, typing.Union, typing.Literal, pytypes.UnionType)
    )


def collect(module: pytypes.ModuleType) -> tuple[dict[str, dict[str, Any]], dict[str, dict[str, Any]], dict[str, dict[str, Any]]]:
    """Schemas of every schema-bearing name in `module.__all__`.

    Returns `(files, defs, aliases)`:
      files    export name -> the self-contained schema written to `<name>.schema.json`
      defs     named model/enum schemas, merged over all files (TypeScript `interface`/`type` per entry)
      aliases  export name -> schema of an exported union alias (TypeScript `type X = A | B`)
    """
    from pydantic import BaseModel, TypeAdapter

    names = list(module.__all__)
    if len(set(names)) != len(names):
        raise ExportError(f"{module.__name__}.__all__ lists a name twice")

    files: dict[str, dict[str, Any]] = {}
    defs: dict[str, dict[str, Any]] = {}
    aliases: dict[str, dict[str, Any]] = {}

    def add_def(name: str, schema: dict[str, Any], where: str) -> None:
        if name in defs and defs[name] != schema:
            raise ExportError(f"two different schemas are named {name!r} (second one from {where})")
        defs[name] = schema

    for name in sorted(names):
        obj = getattr(module, name)
        if not _is_schema_type(obj):
            if isinstance(obj, type) and not issubclass(obj, BaseException):
                raise ExportError(
                    f"{module.__name__}.{name} is a class but not a pydantic model or enum, so it has no schema: "
                    "make it a model, or do not export it from the package"
                )
            continue
        is_named = isinstance(obj, type)
        if is_named and obj.__name__ != name:
            raise ExportError(f"{module.__name__}.{name} is the class {obj.__name__!r}: export a class under its own name")

        schema = obj.model_json_schema() if isinstance(obj, type) and issubclass(obj, BaseModel) else TypeAdapter(obj).json_schema()
        inner = dict(schema.pop("$defs", {}))
        for def_name, def_schema in inner.items():
            add_def(def_name, def_schema, name)

        if is_named:
            if set(schema) == {"$ref"}:  # a recursive model: pydantic already put it in $defs
                if schema["$ref"] != f"#/$defs/{name}":
                    raise ExportError(f"{name}: unexpected root {schema['$ref']!r}")
            else:
                add_def(name, schema, name)
        else:
            aliases[name] = schema

        file_schema = {"$schema": SCHEMA_DIALECT, **schema}
        if inner:
            file_schema["$defs"] = dict(sorted(inner.items()))
        files[name] = file_schema

    if not files:
        raise ExportError(f"{module.__name__}.__all__ exports no schema-bearing names")
    clash = sorted(set(defs) & set(aliases))
    if clash:
        raise ExportError(f"a union alias shares its name with a model: {clash}")
    return files, defs, aliases


def render(module: pytypes.ModuleType) -> dict[str, str]:
    """Output file name -> exact text, for every file the current models produce."""
    files, defs, aliases = collect(module)
    out = {
        f"{name}{SCHEMA_SUFFIX}": json.dumps(schema, indent=2, ensure_ascii=False) + "\n" for name, schema in files.items()
    }
    out[TYPES_FILE] = HEADER + render_declarations(defs, aliases)
    return out


def _generated_on_disk(out_dir: Path) -> set[str]:
    if not out_dir.is_dir():
        return set()
    return {p.name for p in out_dir.iterdir() if p.is_file() and (p.name.endswith(SCHEMA_SUFFIX) or p.name == TYPES_FILE)}


def diff(out_dir: Path, rendered: dict[str, str]) -> list[str]:
    """One line per way `out_dir` differs from `rendered`; empty when they match exactly."""
    problems = []
    for name in sorted(rendered):
        path = out_dir / name
        if not path.is_file():
            problems.append(f"missing: {name}")
        elif path.read_text(encoding="utf-8") != rendered[name]:
            problems.append(f"differs: {name}")
    for name in sorted(_generated_on_disk(out_dir) - set(rendered)):
        problems.append(f"stale (no model produces it): {name}")
    return problems


def write(out_dir: Path, rendered: dict[str, str]) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    for name in sorted(_generated_on_disk(out_dir) - set(rendered)):
        (out_dir / name).unlink()
    for name, text in rendered.items():
        path = out_dir / name
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8", newline="\n")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 if the files on disk differ")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT, help="output directory (default: <repo>/schemas)")
    args = ap.parse_args(argv)

    import kinetra_core

    try:
        rendered = render(kinetra_core)
    except ExportError as e:
        print(f"export_schemas: {e}", file=sys.stderr)
        return 1
    schema_count = sum(1 for n in rendered if n.endswith(SCHEMA_SUFFIX))

    if args.check:
        problems = diff(args.out, rendered)
        if problems:
            print(f"schemas out of date ({len(problems)} problem(s)):", file=sys.stderr)
            for p in problems:
                print(f"  {p}", file=sys.stderr)
            print("run: uv run python packages/core/scripts/export_schemas.py", file=sys.stderr)
            return 1
        print(f"schemas up to date: {schema_count} schema files + {TYPES_FILE} in {args.out}")
        return 0

    write(args.out, rendered)
    print(f"wrote {schema_count} schema files + {TYPES_FILE} to {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
