#!/usr/bin/env python
"""Export JSON Schema + TypeScript types for the physlab contracts.

    uv run python packages/core/scripts/export_schemas.py

Writes (relative to repo root):
    schemas/spec_sheet.schema.json   (validation-mode: what the validator accepts; defaults optional)
    schemas/trajectory.schema.json
    schemas/verdict.schema.json
    schemas/types.ts                 (generated from serialization-mode schemas: the fully
                                      populated form that Python emits, so defaulted fields are
                                      required in TS)

The TS generator below is a tiny built-in converter (no node tooling needed) that covers the
JSON-Schema subset pydantic emits: $ref/$defs, enum, const, anyOf, arrays/tuples, objects,
additionalProperties maps.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "packages" / "core" / "src"))

from physlab_core.schemas import EXTRA_MODELS, MODELS, SCHEMA_VERSION  # noqa: E402

OUT = ROOT / "schemas"
ROOT_NAMES = {"spec_sheet": "SpecSheet", "trajectory": "Trajectory", "verdict": "Verdict", "design_brief": "DesignBrief"}


# ----------------------------- JSON Schema -> TS ----------------------------- #

def _lit(v) -> str:
    return json.dumps(v)


def ts_type(s: dict, indent: int = 0) -> str:
    if "$ref" in s:
        return s["$ref"].rsplit("/", 1)[-1]
    if "const" in s:
        return _lit(s["const"])
    if "enum" in s:
        return " | ".join(_lit(v) for v in s["enum"])
    if "anyOf" in s or "oneOf" in s:
        parts = [ts_type(x, indent) for x in s.get("anyOf", s.get("oneOf"))]
        out: list[str] = []
        for p in parts:
            if p not in out:
                out.append(p)
        return " | ".join(out)
    t = s.get("type")
    if isinstance(t, list):
        return " | ".join(ts_type({**s, "type": x}, indent) for x in t)
    if t == "string":
        return "string"
    if t in ("number", "integer"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        items = s.get("items", {})
        inner = ts_type(items, indent)
        lo, hi = s.get("minItems"), s.get("maxItems")
        if lo is not None and lo == hi and lo <= 8:
            return "[" + ", ".join([inner] * lo) + "]"
        if " | " in inner:
            inner = f"({inner})"
        return f"{inner}[]"
    if t == "object" or "properties" in s:
        props = s.get("properties")
        if not props:
            ap = s.get("additionalProperties")
            if isinstance(ap, dict):
                return f"Record<string, {ts_type(ap, indent)}>"
            return "Record<string, unknown>"
        pad = "  " * (indent + 1)
        req = set(s.get("required", []))
        lines = ["{"]
        for k, v in props.items():
            if v.get("description"):
                lines.append(f"{pad}/** {' '.join(v['description'].split())} */")
            lines.append(f"{pad}{k}{'' if k in req else '?'}: {ts_type(v, indent + 1)};")
        lines.append("  " * indent + "}")
        return "\n".join(lines)
    return "unknown"


def gen_ts(schemas: dict[str, dict]) -> str:
    chunks = [
        "// GENERATED by packages/core/scripts/export_schemas.py -- do not edit by hand.",
        f"// schema_version {SCHEMA_VERSION}",
        "// Conventions: SI units; world frame +Z up (MuJoCo); quaternions are [w,x,y,z] (Three.js wants [x,y,z,w]).",
        "",
    ]
    seen: set[str] = set()
    for key, sch in schemas.items():
        defs = sch.get("$defs", {})
        for name, d in defs.items():
            if name in seen:
                continue
            seen.add(name)
            chunks.append(_decl(name, d))
        root = ROOT_NAMES[key]
        body = {k: v for k, v in sch.items() if k != "$defs"}
        seen.add(root)
        chunks.append(_decl(root, body))
    return "\n".join(chunks)


def _decl(name: str, d: dict) -> str:
    doc = f"/** {' '.join(d['description'].split())} */\n" if d.get("description") else ""
    t = ts_type(d)
    if t.startswith("{"):
        return f"{doc}export interface {name} {t}\n"
    return f"{doc}export type {name} = {t};\n"


# ---------------------------------- main ------------------------------------ #

def main() -> None:
    OUT.mkdir(exist_ok=True)
    ser: dict[str, dict] = {}
    for key, model in {**MODELS, **EXTRA_MODELS}.items():
        val = model.model_json_schema(mode="validation")
        val["$schema"] = "https://json-schema.org/draft/2020-12/schema"
        (OUT / f"{key}.schema.json").write_text(json.dumps(val, indent=2, ensure_ascii=False) + "\n")
        ser[key] = model.model_json_schema(mode="serialization")
        print(f"wrote schemas/{key}.schema.json")
    (OUT / "types.ts").write_text(gen_ts(ser))
    print("wrote schemas/types.ts")


if __name__ == "__main__":
    main()
